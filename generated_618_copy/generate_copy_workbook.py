def clear_sheet(ws):
    for merged_range in list(ws.merged_cells.ranges):
        ws.unmerge_cells(str(merged_range))
    if ws.max_row:
        ws.delete_rows(1, ws.max_row)
    if ws.max_column:
        ws.delete_cols(1, ws.max_column)


def style_range(ws, max_row, max_col):
    orange = "F26A21"
    pale = "FFF4E8"
    dark = "333333"
    thin = Side(style="thin", color="E5E0D8")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    for row in ws.iter_rows(min_row=1, max_row=max_row, min_col=1, max_col=max_col):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            cell.border = border
            cell.font = Font(name="微软雅黑", size=11, color=dark)
    for cell in ws[1]:
        cell.fill = PatternFill("solid", fgColor=orange)
        cell.font = Font(name="微软雅黑", size=12, bold=True, color="FFFFFF")
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for r in range(2, max_row + 1):
        if r % 2 == 0:
            for c in range(1, max_col + 1):
                ws.cell(r, c).fill = PatternFill("solid", fgColor=pale)


def write_table(ws, headers, rows, widths):
    clear_sheet(ws)
    for col_idx, header in enumerate(headers, start=1):
        ws.cell(1, col_idx, header)
    for row_idx, row in enumerate(rows, start=2):
        for col_idx, value in enumerate(row, start=1):
            ws.cell(row_idx, col_idx, value)
    for col_letter, width in widths.items():
        ws.column_dimensions[col_letter].width = width
    for r in range(1, len(rows) + 2):
        ws.row_dimensions[r].height = 80 if r > 1 else 28
    style_range(ws, len(rows) + 1, len(headers))


